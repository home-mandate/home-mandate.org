// Checks the conformance reports pinned in src/lib/content/implementations.ts and
// writes src/lib/generated/conformance.ts with the classes they show as passed.
// Every report must lie under the project's URL, is downloaded (cached in
// .spec-cache/conformance/ by its SHA-256), must match its pinned SHA-256,
// must have run the cases of the specification
// version the entry names (manifest digest of .spec-cache/<spec>, imported by
// scripts/import-spec.ts) and must pass every declared class it covers.
// Any contradiction fails the build. Run with: node scripts/import-conformance.ts
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { IMPLEMENTATIONS, type Implementation } from '../src/lib/content/implementations.ts';
import { checkDigest, checkReportUrl, parseReport, passedClasses, type PassedClass } from './lib/conformance.ts';
import { sha256 } from './lib/spec.ts';

const ROOT = new URL('..', import.meta.url).pathname;
const CACHE = join(ROOT, '.spec-cache', 'conformance');
const OUT = join(ROOT, 'src', 'lib', 'generated', 'conformance.ts');
const HEX64 = /^[0-9a-f]{64}$/;
const FETCH_TIMEOUT_MS = 30_000;

interface Verified {
	run: string;
	classes: Record<string, PassedClass>;
}

async function download(url: string, pinned: string): Promise<Buffer> {
	if (!url.startsWith('https://')) throw new Error('not https');
	if (!HEX64.test(pinned)) throw new Error('sha256 is not 64 hex digits');
	const cached = join(CACHE, `${pinned}.json`);
	if (existsSync(cached)) {
		const data = readFileSync(cached);
		if (sha256(data) === pinned) return data;
	}
	const response = await fetch(url, { signal: AbortSignal.timeout(FETCH_TIMEOUT_MS) });
	if (!response.ok) throw new Error(`HTTP ${response.status}`);
	const data = Buffer.from(await response.arrayBuffer());
	const mismatch = checkDigest(data, pinned);
	if (mismatch !== undefined) throw new Error(mismatch);
	mkdirSync(CACHE, { recursive: true });
	writeFileSync(cached, data);
	return data;
}

async function verify(impl: Implementation): Promise<Verified | undefined> {
	if (impl.conformance === undefined) return undefined;
	const { run, reports } = impl.conformance;
	if (!run.startsWith('https://')) throw new Error(`${impl.name}: run link is not https`);
	if (reports.length === 0) throw new Error(`${impl.name}: conformance without reports`);
	const manifestPath = join(ROOT, '.spec-cache', impl.spec, 'conformance', 'manifest.json');
	if (!existsSync(manifestPath)) throw new Error(`${impl.name}: specification ${impl.spec} is not imported (spec.lock.json)`);
	const manifest = sha256(readFileSync(manifestPath));

	const parsed = [];
	for (const { url, sha256: pinned } of reports) {
		try {
			const foreign = checkReportUrl(impl.url, url);
			if (foreign !== undefined) throw new Error(foreign);
			parsed.push(parseReport(await download(url, pinned)));
		} catch (error) {
			throw new Error(`${impl.name}: ${url}: ${(error as Error).message}`, { cause: error });
		}
	}
	const { classes, errors } = passedClasses(impl.classes, parsed, manifest);
	if (errors.length > 0) throw new Error(`${impl.name}:\n  ${errors.join('\n  ')}`);
	return { run, classes };
}

async function main(): Promise<void> {
	const verified: Record<string, Verified> = {};
	for (const impl of IMPLEMENTATIONS) {
		const result = await verify(impl);
		if (result === undefined) continue;
		verified[impl.name] = result;
		console.log(`Conformance ${impl.name}: ${Object.keys(result.classes).join(', ') || 'no class'} passed`);
	}
	mkdirSync(join(ROOT, 'src', 'lib', 'generated'), { recursive: true });
	writeFileSync(
		OUT,
		'// Generated by scripts/import-conformance.ts - do not edit.\n' +
			'export const conformance: Record<string, { run: string; classes: Record<string, { cases: number; passed: number }> }> = ' +
			`${JSON.stringify(verified, null, '\t')};\n`
	);
}

await main();
